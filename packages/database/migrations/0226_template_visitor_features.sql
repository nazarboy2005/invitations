ALTER TABLE templates ADD CONSTRAINT template_visitor_features_shape CHECK (
  jsonb_typeof(visitor_features)='object'
  AND visitor_features ?& ARRAY['rsvp','wishes','receipts','giftIntentions']
  AND visitor_features->>'rsvp' IN ('none','deadline','phone','form')
  AND jsonb_typeof(visitor_features->'rsvp')='string'
  AND jsonb_typeof(visitor_features->'wishes')='boolean'
  AND jsonb_typeof(visitor_features->'receipts')='boolean'
  AND jsonb_typeof(visitor_features->'giftIntentions')='boolean'
  AND visitor_features - ARRAY['rsvp','wishes','receipts','giftIntentions'] = '{}'::jsonb
);
